МОДЕЛЬ_КОРРЕКЦИИ = "ai-forever/sage-fredt5-distilled-95m"
СТРОКА_ПОХОЖА_НА_ФИО = re.compile(
    r"^[А-ЯЁ][а-яё-]+(?:\s+[А-ЯЁ][а-яё-]+){0,3}$"
)
СЛОВАРЬ_ДИПЛОМНЫХ_СЛОВ = (
    "ДИПЛОМ",
    "БАКАЛАВРА",
    "БАКАЛАВР",
    "БАКАЛАВРИАТ",
    "БАКАЛАВРИАТА",
    "БАКАЛАВРИАТЕ",
    "МАГИСТРА",
    "МАГИСТР",
    "МАГИСТРАТУРА",
    "МАГИСТРАТУРЫ",
    "МАГИСТРАТУРЕ",
    "СПЕЦИАЛИСТА",
    "СПЕЦИАЛИСТ",
    "СПЕЦИАЛИТЕТ",
    "СПЕЦИАЛИТЕТА",
    "ОТЛИЧИЕМ",
)
НАПРАВЛЕНИЯ_ПО_КОДУ = {"09.03.04": "Программная инженерия"}


def исправить_термины_диплома(текст: str) -> tuple[str, bool]:
    """Сверяет OCR-слова с ограниченным списком типичных дипломных терминов."""
    были_замены = False

    def заменить(совпадение: re.Match) -> str:
        nonlocal были_замены
        слово = совпадение.group(0)
        норма = слово.upper()
        if len(норма) < 6:
            порог = 0.78 if len(норма) >= 4 else 1.0
        else:
            порог = 0.62

        лучший_термин = max(
            СЛОВАРЬ_ДИПЛОМНЫХ_СЛОВ,
            key=lambda термин: difflib.SequenceMatcher(
                None, норма, термин
            ).ratio(),
        )
        сходство = difflib.SequenceMatcher(
            None, норма, лучший_термин
        ).ratio()
        if сходство < порог:
            return слово

        if слово.isupper():
            исправленное = лучший_термин
        elif слово.istitle():
            исправленное = лучший_термин.title()
        else:
            исправленное = лучший_термин.lower()
        были_замены = были_замены or исправленное != слово
        return исправленное

    результат = re.sub(r"[А-ЯЁа-яё]+", заменить, текст)
    return результат, были_замены


def исправить_направление_по_коду(текст: str) -> tuple[str, bool]:
    """Нормализует известное название направления, не меняя его код."""
    метка = " [проверьте распознавание]" if "[проверьте распознавание]" in текст else ""
    чистый_текст = текст.replace(метка, "").strip()
    совпадение = re.match(
        r"^(\s*\d{2}\.\d{2}\.\d{2})(\s+)(.+)$", чистый_текст, re.DOTALL
    )
    if not совпадение:
        return текст, False
    код, разделитель, название = совпадение.groups()
    эталон = НАПРАВЛЕНИЯ_ПО_КОДУ.get(код)
    if эталон is None:
        return текст, False

    # Код направления однозначно задаёт название. Это надёжнее сравнения с
    # повреждённым OCR-текстом и применяется только к известным кодам.
    нормализованное = f"{код}{разделитель}{эталон}{метка}"
    return нормализованное, True


def исправить_квалификацию(текст: str) -> str:
    """Исправляет закрытый список квалификаций, не переписывая поле свободно."""
    без_метки = re.sub(r"\s*\[проверьте распознавание\]", "", текст).strip()
    только_буквы = re.sub(r"[^А-ЯЁа-яё]", "", без_метки).upper()
    варианты = {
        "БАКАЛАВР": "Бакалавр",
        "БАКАЛАВРА": "Бакалавр",
        "МАГИСТР": "Магистр",
        "МАГИСТРА": "Магистр",
        "СПЕЦИАЛИСТ": "Специалист",
        "СПЕЦИАЛИСТА": "Специалист",
    }
    лучший_вариант = max(
        варианты,
        key=lambda вариант: difflib.SequenceMatcher(
            None, только_буквы, вариант
        ).ratio(),
    )
    сходство = difflib.SequenceMatcher(
        None, только_буквы, лучший_вариант
    ).ratio()
    if сходство >= 0.65:
        метка = " [проверьте распознавание]" if "[проверьте распознавание]" in текст else ""
        return варианты[лучший_вариант] + метка

    # Квалификация выбирается из короткого официального списка. Если слово не
    # похоже на один из вариантов, отмечаем его для ручной сверки, а не угадываем.
    if только_буквы:
        return без_метки + " [проверьте распознавание]"
    return текст


class РусскийКорректор:
    """Загружает русскую модель исправления опечаток при запросе пользователя."""

    def __init__(self):
        import torch
        from transformers import AutoModelForSeq2SeqLM, AutoTokenizer

        self.torch = torch
        self.tokenizer = AutoTokenizer.from_pretrained(МОДЕЛЬ_КОРРЕКЦИИ)
        self.model = AutoModelForSeq2SeqLM.from_pretrained(МОДЕЛЬ_КОРРЕКЦИИ)
        self.model.to("cpu")
        self.model.eval()

    def исправить(self, текст: str, разрешить_имена: bool = False) -> str:
        исходный = текст.strip()
        if not исходный or "[не распознано]" in исходный:
            return текст
        if "[проверьте распознавание]" in исходный:
            return текст
        if not разрешить_имена and СТРОКА_ПОХОЖА_НА_ФИО.fullmatch(исходный):
            return текст

        токены = self.tokenizer(
            исходный, return_tensors="pt", truncation=True, max_length=512
        )
        with self.torch.inference_mode():
            результат = self.model.generate(
                **токены,
                num_beams=4,
                do_sample=False,
                max_new_tokens=max(
                    24, min(128, int(токены["input_ids"].shape[1] * 1.8))
                ),
            )
        вариант = self.tokenizer.decode(результат[0], skip_special_tokens=True).strip()
        if not вариант:
            return текст

        # Отбрасываем ответы, слишком непохожие на исходник: корректор должен
        # чинить опечатки, а не переписывать содержимое документа.
        сходство = difflib.SequenceMatcher(
            None, исходный.casefold(), вариант.casefold()
        ).ratio()
        return вариант if сходство >= 0.45 else текст


def исправить_направление(текст: str, корректор: РусскийКорректор) -> str:
    """Исправляет название направления, сохраняя цифровой код без изменений."""
    нормализованное, найдено = исправить_направление_по_коду(текст)
    if найдено:
        return нормализованное
    совпадение = re.match(r"^(\s*\d{2}\.\d{2}\.\d{2}\s+)(.+)$", текст, re.DOTALL)
    if not совпадение:
        return корректор.исправить(текст, разрешить_имена=True)
    код, название = совпадение.groups()
    return код + корректор.исправить(название, разрешить_имена=True)


def исправить_обычный_текст(текст: str, корректор: РусскийКорректор) -> str:
    """Правит строки OCR, оставляя без изменений строки с числами и похожие на ФИО."""
    исправленные_строки = []
    for строка in текст.splitlines():
        очищенная = строка.strip()
        if not очищенная or re.search(r"\d", очищенная):
            исправленные_строки.append(строка)
        elif СТРОКА_ПОХОЖА_НА_ФИО.fullmatch(очищенная):
            исправленные_строки.append(строка)
        else:
            исправленные_строки.append(
                корректор.исправить(очищенная, разрешить_имена=True)
            )
    return "\n".join(исправленные_строки)


def показать_оба_варианта(исходный: str, исправленный: str) -> str:
    return (
        f"Распознано:\n{исходный}\n\n"
        f"После проверки моделью:\n{исправленный}"
    )


# Координаты областей относительно разворота целиком, в долях его ширины и высоты.
# Шаблон рассчитан на макет диплома ЮФУ из приложенного PDF; печать и подпись
# намеренно исключены из областей распознавания. Постоянные строки выводятся
# из текстовой формы ниже, а значения читаются из этих прямоугольников.
ПОЛЯ_ДИПЛОМА = {
    "Вид диплома": (0.08, 0.53, 0.49, 0.75),
    "ФИО": (0.57, 0.16, 0.97, 0.225),
    "Направление подготовки": (0.57, 0.30, 0.97, 0.37),
    "Квалификация": (0.57, 0.625, 0.97, 0.65),
    "Протокол": (0.57, 0.65, 0.97, 0.70),
    "Серия и номер": (0.12, 0.73, 0.52, 0.80),
    "Регистрационный номер": (0.12, 0.89, 0.52, 0.94),
    "Дата выдачи": (0.12, 0.95, 0.52, 0.999),
}


def собрать_строки(результаты) -> list[str]:
    """Группирует найденные фрагменты текста по строкам страницы."""
    фрагменты = []
    for рамка, текст, уверенность in результаты:
        if not текст.strip():
            continue
        координаты = np.asarray(рамка, dtype=float)
        верх = float(np.min(координаты[:, 1]))
        низ = float(np.max(координаты[:, 1]))
        лево = float(np.min(координаты[:, 0]))
        высота = max(1.0, низ - верх)
        фрагменты.append(
            {
                "text": текст.strip(),
                "top": верх,
                "bottom": низ,
                "left": лево,
                "height": высота,
                "confidence": float(уверенность),
            }
        )

    фрагменты.sort(key=lambda ф: ((ф["top"] + ф["bottom"]) / 2, ф["left"]))
    строки: list[dict] = []

    for фрагмент in фрагменты:
        центр = (фрагмент["top"] + фрагмент["bottom"]) / 2
        подходящая_строка = None
        лучшее_расстояние = float("inf")

        for строка in reversed(строки):
            центр_строки = (строка["top"] + строка["bottom"]) / 2
            высота_строки = строка["bottom"] - строка["top"]
            расстояние = abs(центр - центр_строки)
            допуск = 0.55 * max(фрагмент["height"], высота_строки)
            пересечение = max(
                0.0,
                min(фрагмент["bottom"], строка["bottom"])
                - max(фрагмент["top"], строка["top"]),
            )
            доля_пересечения = пересечение / min(
                фрагмент["height"], max(1.0, высота_строки)
            )

            if расстояние <= допуск or доля_пересечения >= 0.35:
                if расстояние < лучшее_расстояние:
                    подходящая_строка = строка
                    лучшее_расстояние = расстояние

        if подходящая_строка is None:
            строки.append(
                {
                    "top": фрагмент["top"],
                    "bottom": фрагмент["bottom"],
                    "parts": [фрагмент],
                }
            )
        else:
            подходящая_строка["top"] = min(
                подходящая_строка["top"], фрагмент["top"]
            )
            подходящая_строка["bottom"] = max(
                подходящая_строка["bottom"], фрагмент["bottom"]
            )
            подходящая_строка["parts"].append(фрагмент)

    строки.sort(key=lambda строка: строка["top"])
    return [
        " ".join(часть["text"] for часть in sorted(строка["parts"], key=lambda ч: ч["left"]))
        for строка in строки
    ]


def распознать_страницу(изображение: Image.Image, распознаватель) -> str:
    """Передаёт одну страницу изображения в OCR-модель."""
    изображение = ImageOps.exif_transpose(изображение).convert("RGB")
    результаты = распознаватель.readtext(
        np.asarray(изображение),
        detail=1,
        paragraph=False,
        batch_size=1,
        min_size=10,
    )
    return "\n".join(собрать_строки(результаты))


def собрать_текст_диплома(поля: dict[str, str]) -> str:
    """Подставляет распознанные значения в постоянные строки макета ЮФУ."""
    return f"""РОССИЙСКАЯ ФЕДЕРАЦИЯ
Федеральное государственное автономное образовательное учреждение высшего
образования «Южный федеральный университет»
город Ростов-на-Дону

{поля['Вид диплома']}
Серия и номер: {поля['Серия и номер']}
ДОКУМЕНТ ОБ ОБРАЗОВАНИИ И О КВАЛИФИКАЦИИ
Регистрационный номер: {поля['Регистрационный номер']}
Дата выдачи: {поля['Дата выдачи']}

Настоящий диплом свидетельствует о том, что
{поля['ФИО']}
освоил(а) программу бакалавриата по направлению подготовки
{поля['Направление подготовки']}
и успешно прошел(ла) государственную итоговую аттестацию
Решением Государственной экзаменационной комиссии
присвоена(ы) квалификация(и)
{поля['Квалификация']}
{поля['Протокол']}
Руководитель организации, осуществляющей образовательную деятельность"""


def распознать_по_шаблону(
    изображение: Image.Image,
    распознаватель,
    корректор: РусскийКорректор | None = None,
    словарная_проверка: bool = False,
) -> str:
    """Распознаёт только переменные поля в известном макете диплома ЮФУ."""
    изображение = ImageOps.exif_transpose(изображение).convert("RGB")
    if изображение.width <= изображение.height:
        raise ValueError(
            "Шаблон диплома рассчитан на альбомный снимок полного разворота. "
            "Поверните изображение так, чтобы обе половины диплома были рядом."
        )

    ширина, высота = изображение.size
    найденные_поля = {}
    for название, (x0, y0, x1, y1) in ПОЛЯ_ДИПЛОМА.items():
        область = изображение.crop(
            (
                round(x0 * ширина),
                round(y0 * высота),
                round(x1 * ширина),
                round(y1 * высота),
            )
        )
        результаты = распознаватель.readtext(
            np.asarray(область),
            detail=1,
            paragraph=False,
            batch_size=1,
            min_size=8,
        )
        текст = "\n".join(собрать_строки(результаты)).strip()
        if not текст:
            отображение = "[не распознано]"
        else:
            средняя_уверенность = sum(
                float(результат[2]) for результат in результаты
            ) / len(результаты)
            отображение = текст
            if средняя_уверенность < 0.45:
                отображение += " [проверьте распознавание]"
        найденные_поля[название] = отображение

    # Неизменяемые фразы не отправляются в OCR, поэтому фон и печать не добавляют мусор.
    исходный_текст = собрать_текст_диплома(найденные_поля)
    if корректор is None and not словарная_проверка:
        return исходный_текст

    исправленные_поля = найденные_поля.copy()
    if "[не распознано]" not in исправленные_поля["Вид диплома"]:
        исправленные_поля["Вид диплома"], _ = исправить_термины_диплома(
            исправленные_поля["Вид диплома"]
        )
    if "[не распознано]" not in исправленные_поля["Направление подготовки"]:
        нормализованное, найдено = исправить_направление_по_коду(
            исправленные_поля["Направление подготовки"]
        )
        if найдено:
            исправленные_поля["Направление подготовки"] = нормализованное
        elif корректор is not None:
            исправленные_поля["Направление подготовки"] = исправить_направление(
                исправленные_поля["Направление подготовки"], корректор
            )
    if "[не распознано]" not in исправленные_поля["Квалификация"]:
        исправленные_поля["Квалификация"] = исправить_квалификацию(
            исправленные_поля["Квалификация"]
        )

    return показать_оба_варианта(
        исходный_текст, собрать_текст_диплома(исправленные_поля)
    )


def распознать(
    путь: Path,
    разворот: bool = False,
    шаблон_диплома: bool = False,
    корректор: РусскийКорректор | None = None,
    словарная_проверка_диплома: bool = False,
) -> str:
    """Распознаёт изображение или каждую страницу PDF-файла."""
    register_heif_opener()

    # EasyOCR умеет распознавать русский текст и самостоятельно загружает
    # предварительно обученные веса при первом запуске.
    распознаватель = easyocr.Reader(["ru"], gpu=False, verbose=False)

    def обработать(изображение: Image.Image) -> list[tuple[str | None, str]]:
        if шаблон_диплома:
            return [
                (
                    None,
                    распознать_по_шаблону(
                        изображение,
                        распознаватель,
                        корректор=корректор,
                        словарная_проверка=словарная_проверка_диплома,
                    ),
                )
            ]
        if разворот:
            середина = изображение.width // 2
            области = [
                ("левая половина", изображение.crop((0, 0, середина, изображение.height))),
                (
                    "правая половина",
                    изображение.crop((середина, 0, изображение.width, изображение.height)),
                ),
            ]
        else:
            области = [(None, изображение)]
        обработанные = []
        for название, область in области:
            исходный_текст = распознать_страницу(область, распознаватель)
            if корректор is None:
                текст = исходный_текст
            else:
                исправленный_текст = исправить_обычный_текст(
                    исходный_текст, корректор
                )
                текст = показать_оба_варианта(исходный_текст, исправленный_текст)
            обработанные.append((название, текст))
        return обработанные

    if путь.suffix.lower() == ".pdf":
        результаты_страниц = []
        with pymupdf.open(str(путь)) as документ:
            if документ.page_count == 0:
                raise ValueError("В PDF нет страниц.")
            for номер, страница in enumerate(документ, start=1):
                пиксели = страница.get_pixmap(
                    matrix=pymupdf.Matrix(1, 1),
                    colorspace=pymupdf.csRGB,
                    alpha=False,
                )
                изображение = Image.frombytes(
                    "RGB", (пиксели.width, пиксели.height), пиксели.samples
                )
                for название, текст in обработать(изображение):
                    результаты_страниц.append((номер, название, текст))

        if not any(текст.strip() for _, _, текст in результаты_страниц):
            raise ValueError("На страницах PDF не удалось найти текст.")
        if len(результаты_страниц) == 1 and not разворот:
            return результаты_страниц[0][2]

        размеченные_страницы = []
        for номер, название, текст in результаты_страниц:
            заголовок = f"Страница {номер}"
            if название:
                заголовок += f" — {название}"
            размеченные_страницы.append(
                f"{заголовок}\n{текст}" if текст else заголовок
            )
        return "\n\n".join(размеченные_страницы)

    with Image.open(путь) as исходное_изображение:
        исходное_изображение = ImageOps.exif_transpose(исходное_изображение).convert("RGB")
        return "\n".join(текст for _, текст in обработать(исходное_изображение))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Распознаёт печатный русский текст на фото, скане или в PDF."
    )
    parser.add_argument(
        "файл", type=Path, help="Путь к JPG, PNG, HEIC или PDF"
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Файл для результата .txt; если не указан, текст выводится в терминал",
    )
    parser.add_argument(
        "--spread",
        action="store_true",
        help="Разделить каждую страницу PDF на левую и правую половины",
    )
    parser.add_argument(
        "--diploma-template",
        action="store_true",
        help=(
            "Распознать поля диплома бакалавра ЮФУ по шаблону из примера; "
            "подходит для полного альбомного разворота"
        ),
    )
    parser.add_argument(
        "--correct",
        action="store_true",
        help=(
            "После OCR запустить русскую модель коррекции опечаток; "
            "сохранить рядом исходный и исправленный варианты"
        ),
    )
    args = parser.parse_args()

    if not args.файл.is_file():
        parser.error(f"Файл не найден: {args.файл}")
    if args.spread and args.файл.suffix.lower() != ".pdf":
        parser.error("Параметр --spread можно использовать только с PDF-файлом.")
    if args.spread and args.diploma_template:
        parser.error("Параметры --spread и --diploma-template нельзя использовать вместе.")

    try:
        # В шаблоне диплома используются проверяемые словари; большая модель
        # коррекции нужна только для свободного текста и неизвестных полей.
        корректор = (
            РусскийКорректор() if args.correct and not args.diploma_template else None
        )
        текст = распознать(
            args.файл,
            разворот=args.spread,
            шаблон_диплома=args.diploma_template,
            корректор=корректор,
            словарная_проверка_диплома=args.correct,
        )
        if not текст.strip():
            raise ValueError("Не удалось найти текст на изображении.")
    except ImportError as ошибка:
        parser.exit(
            1,
            "Не удалось загрузить библиотеку корректора. Установите зависимости: "
            f"python3 -m pip install -r requirements.txt\nПодробности: {ошибка}\n",
        )
    except Exception as ошибка:
        parser.exit(1, f"Не удалось обработать файл: {ошибка}\n")

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(текст + ("\n" if текст else ""), encoding="utf-8")
        print(f"Текст сохранён в файл: {args.output}")
    else:
        print(текст)


if __name__ == "__main__":
    main()
