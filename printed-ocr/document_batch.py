"""Документы и повторно используемые модели для пакетного распознавания.

Импорт этого модуля не загружает OCR и нейросети: интерфейс может открыться
сразу, а модели подготавливаются в рабочем потоке при первом распознавании.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class ТипДокумента:
    код: str
    название: str
    описание: str
    паспорт: bool = False


ТИПЫ_ДОКУМЕНТОВ = (
    ТипДокумента(
        "diploma",
        "Диплом",
        "Добавьте фото или PDF диплома. Для разворота диплома ЮФУ доступен шаблон.",
    ),
    ТипДокумента(
        "foreign_passport",
        "Заграничный паспорт",
        "Добавьте фото или PDF паспорта. Русский и латинский текст распознаются вместе.",
        паспорт=True,
    ),
    ТипДокумента(
        "diploma_supplement",
        "Приложение к диплому",
        "Добавьте любое количество фото или PDF в порядке чтения.",
    ),
    ТипДокумента(
        "curriculum",
        "Учебный план",
        "Добавьте фото, PDF или DOCX учебного плана. Из DOCX читаются текст и таблицы.",
    ),
)
_ТИПЫ_ПО_КОДУ = {тип.код: тип for тип in ТИПЫ_ДОКУМЕНТОВ}

ДОПУСТИМЫЕ_РАСШИРЕНИЯ = frozenset({".jpg", ".jpeg", ".png", ".heic", ".pdf"})


def расширения_раздела(код: str) -> frozenset[str]:
    if код not in _ТИПЫ_ПО_КОДУ:
        raise ValueError(f"Неизвестный тип документа: {код}")
    return ДОПУСТИМЫЕ_РАСШИРЕНИЯ | {".docx"} if код == "curriculum" else ДОПУСТИМЫЕ_РАСШИРЕНИЯ


def форматы_раздела(код: str) -> str:
    return "JPG, JPEG, PNG, HEIC, PDF" + (", DOCX" if код == "curriculum" else "")



@dataclass(frozen=True)
class Задание:
    категория: str
    путь: Path


@dataclass(frozen=True)
class РезультатФайла:
    задание: Задание
    текст: str = ""
    ошибка: str = ""
    исправления: tuple[str, ...] = ()
    исходный_текст: str = ""


class СеансРаспознавания:
    """Хранит один распознаватель и корректор для последовательных заданий."""

    def __init__(self) -> None:
        self._ocr = None
        self._распознаватель = None
        self._корректор = None
        self.последние_правки = ()
        self.исходный_текст = ""

    def обработать(
        self,
        задание: Задание,
        проверять: bool = True,
        шаблон_диплома: bool = True,
        прогресс: Callable[[str], None] | None = None,
    ) -> str:
        self.последние_правки = ()
        self.исходный_текст = ""
        тип = _ТИПЫ_ПО_КОДУ.get(задание.категория)
        if тип is None:
            raise ValueError(f"Неизвестный тип документа: {задание.категория}")

        путь = Path(задание.путь)
        if путь.suffix.lower() not in расширения_раздела(задание.категория):
            raise ValueError(f"Для этого раздела поддерживаются: {форматы_раздела(задание.категория)}.")
        if not путь.is_file():
            raise FileNotFoundError(f"Файл недоступен: {путь}")
        # Проверяем доступ до загрузки моделей, чтобы сразу показать ошибку файла.
        with путь.open("rb") as файл:
            файл.read(1)

        def сообщить(сообщение: str) -> None:
            if прогресс is not None:
                прогресс(сообщение)

        if путь.suffix.lower() == ".docx":
            from docx_text import прочитать_docx

            сообщить("Чтение текста и таблиц DOCX…")
            # Электронный текст уже известен: OCR и языковая правка не нужны.
            self.исходный_текст = прочитать_docx(путь)
            return self.исходный_текст

        сообщить("Подготовка распознавания…")
        if self._ocr is None:
            import raspoznat_pechat

            self._ocr = raspoznat_pechat
        if self._распознаватель is None:
            сообщить("Загрузка распознавателя…")
            self._распознаватель = self._ocr.создать_распознаватель(("ru", "en"))

        использовать_шаблон = задание.категория == "diploma" and шаблон_диплома
        # Языковая модель может изменить транслитерацию, MRZ и реквизиты паспорта.
        # Для паспорта сохраняем текст непосредственно из OCR.
        исправлять_моделью = проверять and not использовать_шаблон and not тип.паспорт
        if исправлять_моделью and self._корректор is None:
            сообщить("Подготовка проверки текста…")
            self._корректор = self._ocr.РусскийКорректор()

        def страница(номер: int, всего: int) -> None:
            действие = "Распознавание и проверка" if проверять and not тип.паспорт else "Распознавание"
            сообщить(f"Страница {номер} из {всего}. {действие}…")

        from document_review import исправить_по_словарю
        исходные_страницы = []
        правки = []
        def подготовить_текст(текст):
            исходные_страницы.append(текст)
            if проверять and not тип.паспорт:
                текст, замены = исправить_по_словарю(текст, задание.категория)
                правки.extend(замены)
            return текст

        текст = self._ocr.распознать(
            путь,
            шаблон_диплома=использовать_шаблон,
            корректор=self._корректор if исправлять_моделью else None,
            словарная_проверка_диплома=проверять and использовать_шаблон,
            только_исправленный=проверять,
            распознаватель=self._распознаватель,
            прогресс=страница,
            словарь_текста=подготовить_текст,
        )
        self.исходный_текст = "\n".join(исходные_страницы) or текст
        if проверять and not тип.паспорт:
            текст, замены = исправить_по_словарю(текст, задание.категория)
            правки.extend(замены)
        self.последние_правки = tuple(dict.fromkeys(правки))
        if not текст.strip():
            raise ValueError("Не удалось найти текст в документе.")
        return текст.strip()


def собрать_результаты(
    результаты: Sequence[РезультатФайла], заголовки_разделов: bool = True
) -> str:
    """Объединяет файлы по разделам; заголовки можно скрыть при дописывании."""
    группы: dict[str, list[РезультатФайла]] = {тип.код: [] for тип in ТИПЫ_ДОКУМЕНТОВ}
    for результат in результаты:
        код = результат.задание.категория
        if код not in группы:
            raise ValueError(f"Неизвестный тип документа: {код}")
        группы[код].append(результат)

    разделы = []
    for тип in ТИПЫ_ДОКУМЕНТОВ:
        файлы = []
        for результат in группы[тип.код]:
            текст = (
                f"Ошибка распознавания: {результат.ошибка}"
                if результат.ошибка
                else результат.текст.strip() or "Текст не найден."
            )
            файлы.append(f"Файл: {результат.задание.путь.name}\n{текст}")
        if файлы:
            содержимое = "\n\n".join(файлы)
            if заголовки_разделов:
                содержимое = тип.название + "\n\n" + содержимое
            разделы.append(содержимое)
    return "\n\n".join(разделы)
