"""Словари OCR и объяснимая сверка комплекта. Не обращается к сети или модели."""
from collections import defaultdict
from dataclasses import dataclass, replace
from functools import lru_cache
import json
from pathlib import Path
import re

СЛОВО = re.compile(r"[A-Za-zА-Яа-яЁё]+(?:-[A-Za-zА-Яа-яЁё]+)*")
ИМЕНА = re.compile(r"^(?:ФИО|Ф\.И\.О\.|Фамилия|Имя|Отчество)\s*:", re.I)
ЛАТИНИЦА = str.maketrans('ABCEHKMOPTXYabceopxy', 'АВСЕНКМОРТХУавсеорху')


@lru_cache(maxsize=3)
def словарь(категория):
    if категория not in ('diploma','diploma_supplement','curriculum'):
        return {'replacements':{},'terms':[]}
    путь = Path(__file__).with_name('dictionaries') / (категория+'.json')
    данные = json.loads(путь.read_text(encoding='utf-8'))
    if not isinstance(данные.get('replacements'),dict) or not isinstance(данные.get('terms'),list):
        raise ValueError(f'Неверная структура словаря {путь.name}')
    return данные


def регистр(исходное, новое):
    return новое.upper() if исходное.isupper() else новое.capitalize() if исходное.istitle() else новое


def защищённые_строки(текст):
    строки=текст.splitlines()
    защищены=set()
    фио=re.compile(r"^[А-ЯЁA-Z][а-яёa-z-]+(?:[ \t]+[А-ЯЁA-Z][а-яёa-z-]+){1,3}$")
    for i,строка in enumerate(строки):
        if ИМЕНА.match(строка.strip()) or фио.fullmatch(строка.strip()):
            защищены.add(строка)
            if i and фио.fullmatch(строка.strip()) and re.fullmatch(r'[А-ЯЁA-Z][а-яёa-z-]+',строки[i-1].strip()):
                защищены.add(строки[i-1])
            if ИМЕНА.match(строка.strip()) and строка.rstrip().endswith(':') and i+1<len(строки):
                защищены.add(строки[i+1])
    return защищены


def исправить_по_словарю(текст, категория):
    замены = словарь(категория)['replacements']
    журнал = []
    защищены = защищённые_строки(текст)
    def строка(стр):
        if стр in защищены or ИМЕНА.match(стр.strip()) or '[проверьте распознавание]' in стр or '[не распознано]' in стр:
            return стр
        def слово(м):
            было=м.group()
            стало=замены.get(было.casefold())
            if стало is None:
                return было
            стало=регистр(было,стало)
            журнал.append(f'«{было}» → «{стало}» (словарь {категория})')
            return стало
        return СЛОВО.sub(слово,стр)
    return '\n'.join(строка(стр) for стр in текст.split('\n')), tuple(dict.fromkeys(журнал))


@dataclass(frozen=True)
class Поле:
    вид: str
    значение: str


def поля(текст, категория):
    """Сопоставляем только именованные реквизиты одинакового смысла."""
    результат=[]
    правила={
        'Фамилия':r'Фамилия', 'Имя':r'Имя', 'Отчество':r'Отчество',
        'ФИО':r'ФИО|Ф\.И\.О\.', 'Дата рождения':r'Дата рождения',
        'Код направления':r'Код направления(?: подготовки)?|Направление(?: подготовки)?',
        'Квалификация':r'Квалификация',
    }
    if категория in ('diploma','diploma_supplement'):
        правила['Серия и номер диплома']=r'Серия и номер(?: диплома)?|Номер диплома'
        правила['Дата выдачи диплома']=r'Дата выдачи(?: диплома)?'
    for строка in текст.splitlines():
        for вид,метка in правила.items():
            м=re.fullmatch(r'\s*(?:'+метка+r')\s*:\s*(.+?)\s*',строка,re.I)
            if м and '[' not in м[1]:
                значение=м[1]
                if вид=='Код направления':
                    код=re.search(r'\b\d{2}\.\d{2}\.\d{2}\b',значение)
                    if not код: continue
                    значение=код[0]
                результат.append(Поле(вид,значение))
        if категория!='foreign_passport':
            код=re.match(r'^\s*(\d{2}\.\d{2}\.\d{2})\b',строка)
            if код: результат.append(Поле('Код направления',код[1]))
    # Сравниваем часы только при явно подписанных колонках, не угадывая
    # смысл чисел в произвольных OCR-строках или матрицах учебного плана.
    if категория in ('diploma_supplement','curriculum'):
        колонка_названия = колонка_часов = None
        for строка in текст.splitlines():
            if '|' not in строка:
                колонка_названия = колонка_часов = None
                continue
            ячейки=[я.strip() for я in строка.split('|')]
            заголовки=[норма(я) for я in ячейки]
            названия={'дисциплина','наименование дисциплины','наименование дисциплин'}
            часы={'часы','всего часов','количество часов'}
            if any(я in названия for я in заголовки) and any(я in часы for я in заголовки):
                колонка_названия=next(i for i,я in enumerate(заголовки) if я in названия)
                колонка_часов=next(i for i,я in enumerate(заголовки) if я in часы)
                continue
            if колонка_названия is None or max(колонка_названия,колонка_часов)>=len(ячейки): continue
            название=ячейки[колонка_названия]
            число=ячейки[колонка_часов]
            if re.fullmatch(r'[А-Яа-яЁё -]{4,100}',название) and re.fullmatch(r'\d+(?:[.,]\d+)?',число):
                результат.append(Поле('Часы: '+норма(название),число))
    # Макет диплома: ФИО стоит между постоянными фразами.
    м=re.search(r'свидетельствует\s+о\s+том,?\s+что\s*\n(.+?)\n\s*освоил',текст,re.I|re.S)
    if м:
        имя=' '.join(м[1].split())
        if re.fullmatch(r'[А-Яа-яЁёA-Za-z-]+(?: [А-Яа-яЁёA-Za-z-]+){1,3}',имя):
            результат.append(Поле('ФИО',имя))
    м=re.search(r'присвоена(?:\(ы\))?\s+квалификация(?:\(и\))?\s*\n([^\n]+)',текст,re.I)
    if м and '[' not in м[1]: результат.append(Поле('Квалификация',м[1].strip()))
    # Раздельные подписанные ФИО в паспорте сопоставимы с полным ФИО диплома.
    части={п.вид:п.значение for п in результат if п.вид in ('Фамилия','Имя','Отчество')}
    if all(к in части for к in ('Фамилия','Имя','Отчество')):
        результат.append(Поле('ФИО',' '.join(части[к] for к in ('Фамилия','Имя','Отчество'))))
    return list(dict.fromkeys(результат))


def норма(значение):
    return ' '.join(значение.casefold().replace('ё','е').split())


def похожая_ошибка(было, эталон):
    """Только смешение алфавитов или одна типичная буквенная OCR-подмена."""
    а,б=было.casefold(),эталон.casefold()
    if len(а)!=len(б) or len(а)<6 or а==б: return False
    отличия=[(x,y) for x,y in zip(а,б) if x!=y]
    пары=[set('ин'),set('лп'),set('шщ')]
    return len(отличия)==1 and (set(отличия[0]) in пары or а.translate(ЛАТИНИЦА)==б)


def сверить_комплект(результаты, *, неполный=False):
    """Возвращает новые результаты и журнал. Не исправляет паспорт, ФИО и цифры."""
    записи=list(результаты)
    журнал=[]
    if неполный or any(р.ошибка for р in записи):
        журнал.append('Сверка неполная: использованы только успешно обработанные файлы.')
    успешные=[(i,р) for i,р in enumerate(записи) if not р.ошибка and р.текст.strip()]
    источник=lambda р: str(р.задание.путь.resolve())
    имя=lambda р: f'{р.задание.категория}/{р.задание.путь.name}'
    for _,р in успешные:
        for правка in р.исправления:
            журнал.append(f'{имя(р)}: {правка}')
    сведения=defaultdict(list)
    for i,р in успешные:
        for п in поля(р.текст,р.задание.категория):
            сведения[п.вид].append((i,п.значение))
    сравнения=0
    несовместимы=False
    for вид,значения in сведения.items():
        if len({источник(записи[i]) for i,_ in значения})<2: continue
        сравнения+=1
        варианты=defaultdict(list)
        for i,значение in значения:
            ключ=норма(значение)
            if вид=='Серия и номер диплома' and re.fullmatch(r'[\d\s]+',значение):
                ключ=''.join(значение.split())
            варианты[ключ].append((i,значение))
        if len(варианты)==1:
            журнал.append(f'Совпадает: {вид} — {значения[0][1]}. Источники: '+', '.join(dict.fromkeys(имя(записи[i]) for i,_ in значения)))
        else:
            журнал.append(f'[ПРОВЕРЬТЕ] {вид}: '+ '; '.join(f'{имя(записи[i])}: «{v}»' for i,v in значения)+'. Значения сохранены.')
            if вид in ('ФИО','Фамилия','Имя','Отчество','Код направления'):
                несовместимы=True
    if not сравнения:
        журнал.append('Общих подписанных реквизитов для сравнения не найдено. Это не подтверждает согласованность документов.')

    # Эталонные слова берём из исходного DOCX или из совпадений минимум в двух
    # разных файлах и разделах. Повтор одной фотографии не считается подтверждением.
    словники=defaultdict(set)
    docx=set()
    разрешенные=set()
    for тип in ('diploma','diploma_supplement','curriculum'):
        разрешенные.update(словарь(тип)['terms'])
    for i,р in успешные:
        if р.задание.категория=='foreign_passport': continue
        if р.задание.категория=='diploma': continue  # Шаблонные фразы не являются независимым OCR-подтверждением.
        исходный=р.исходный_текст or р.текст
        защищены=защищённые_строки(исходный)
        for стр in исходный.splitlines():
            if стр in защищены or ИМЕНА.match(стр.strip()) or '[' in стр: continue
            for м in СЛОВО.finditer(стр):
                слово=м[0].casefold()
                if слово in разрешенные:
                    словники[слово].add(i)
                    if р.задание.путь.suffix.lower()=='.docx': docx.add(слово)
    эталоны={слово for слово,индексы in словники.items()
             if слово in docx or (len({источник(записи[i]) for i in индексы})>=2
                                 and len({записи[i].задание.категория for i in индексы})>=2)}
    исправлено=0
    if not несовместимы:
        for i,р in успешные:
            if р.задание.категория=='foreign_passport' or р.задание.путь.suffix.lower()=='.docx': continue
            защищены=защищённые_строки(р.текст)
            def строка(стр):
                if стр in защищены or ИМЕНА.match(стр.strip()) or '[' in стр: return стр
                def заменить(м):
                    nonlocal исправлено
                    было=м[0]
                    if было.casefold() in разрешенные: return было
                    кандидаты=[э for э in эталоны if похожая_ошибка(было,э)
                               and any(источник(записи[j])!=источник(р) for j in словники[э])]
                    if len(кандидаты)!=1: return было
                    эталон=кандидаты[0]; стало=регистр(было,эталон)
                    подтверждения=', '.join(dict.fromkeys(имя(записи[j]) for j in sorted(словники[эталон]) if источник(записи[j])!=источник(р)))
                    журнал.append(f'{имя(р)}: «{было}» → «{стало}». Подтверждение: {подтверждения}.')
                    исправлено+=1
                    return стало
                return СЛОВО.sub(заменить,стр)
            записи[i]=replace(р,текст='\n'.join(строка(стр) for стр in р.текст.split('\n')))
    else:
        журнал.append('Автоисправления по другим файлам отключены: расходятся ФИО или код направления. Проверьте состав комплекта.')
    журнал.insert(0,f'Автоисправлений по другим файлам: {исправлено}. Числовые расхождения и ФИО требуют сверки с оригиналами.')
    return записи, 'СВЕРКА КОМПЛЕКТА\n'+'\n'.join(журнал)
